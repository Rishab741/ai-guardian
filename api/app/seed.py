async def bootstrap() -> None:
    tenant = config.DEFAULT_TENANT
    pool = await db.get_pool()
    async with pool.acquire() as conn:
        async with conn.transaction():
            await conn.execute(
                "insert into tenants (id, name, settings) values ($1, $2, $3) on conflict (id) do nothing",
                tenant, TENANT_NAME, {"privacy_mode": "named", "store_content": True},
            )
            for dept_id, label in policy.DEFAULT_DEPARTMENTS:
                await conn.execute(
                    "insert into departments (tenant_id, id, label) values ($1, $2, $3) on conflict do nothing",
                    tenant, dept_id, label,
                )
            has_policy = await conn.fetchval("select exists(select 1 from policies where tenant_id = $1)", tenant)
            if not has_policy:
                await conn.execute(
                    """insert into policies (tenant_id, version, doc, status, created_by, approved_by, approved_at)
                       values ($1, 1, $2, 'active', 'system', 'system', now())""",
                    tenant, policy.DEFAULT_POLICY,
                )
            for name, dept, desc in APPS:
                await conn.execute(
                    """insert into apps (tenant_id, name, description, default_department) values ($1, $2, $3, $4)
                       on conflict (tenant_id, name) do nothing""",
                    tenant, name, desc, dept,
                )
        advisor_id = await conn.fetchval("select id from apps where tenant_id = $1 and name = 'Advisor Assist'", tenant)
        has_key = await conn.fetchval("select exists(select 1 from app_keys where app_id = $1)", advisor_id)

    if config.DEMO_APP_KEY:
        await identity.create_key(advisor_id, config.DEMO_APP_KEY)
    elif not has_key:
        key = await identity.create_key(advisor_id)
        # Shown once, like any API key. Set SF_DEMO_APP_KEY to pin it.
        log.warning("Created API key for 'Advisor Assist' (shown once): %s", key)


def _workforce(rng: random.Random) -> list[dict]:
    people, used = [], set()
    risky_quota = {"technology": 1, "finance": 1, "retail_banking": 2, "hr": 1}
    for dept, _ in policy.DEFAULT_DEPARTMENTS:
        for i in range(12):
            while True:
                first, last = rng.choice(_FIRST), rng.choice(_LAST)
                if (first, last) not in used:
                    used.add((first, last))
                    break
            risky = risky_quota.get(dept, 0) > 0 and i < risky_quota.get(dept, 0)
            people.append({
                "id": f"{first}.{last}".lower(),
                "external_ref": f"{first}.{last}@harbourbank.example".lower(),
                "display_name": f"{first} {last}",
                "title": rng.choice(_TITLES[dept]),
                "department": dept,
                "profile": "risky" if risky else rng.choice(["careful", "normal", "normal"]),
            })
    return people


_PII_PROB = {"careful": 0.06, "normal": 0.18, "risky": 0.62}


async def seed_demo(days: int = 90, target: int = 3200) -> None:
    tenant = config.DEFAULT_TENANT
    pool = await db.get_pool()
    async with pool.acquire() as conn:
        if await conn.fetchval("select exists(select 1 from audit_events where tenant_id = $1)", tenant):
            return
        apps = await conn.fetch("select id, name, default_department from apps where tenant_id = $1", tenant)

    rng = random.Random(20261014)
    people = _workforce(rng)
    async with pool.acquire() as conn:
        await conn.executemany(
            """insert into end_users (tenant_id, id, external_ref, display_name, title, department, synthetic)
               values ($1, $2, $3, $4, $5, $6, true) on conflict do nothing""",
            [(tenant, p["id"], p["external_ref"], p["display_name"], p["title"], p["department"]) for p in people],
        )

    apps_by_dept: dict[str, list] = {}
    for a in apps:
        apps_by_dept.setdefault(a["default_department"], []).append(a)

    active = await policy.get_active(tenant)
    now = datetime.now(timezone.utc)
    events = []
    for _ in range(target):
        # Adoption ramp: denser in recent weeks; business hours in Sydney.
        day = int(days * (1 - rng.random() ** 0.55))
        ts = (now - timedelta(days=day)).replace(hour=rng.randint(21, 23) if rng.random() < 0.3 else rng.randint(0, 7),
                                                 minute=rng.randint(0, 59), second=rng.randint(0, 59))
        if ts > now:
            ts -= timedelta(days=1)
        person = rng.choice(people)
        app = rng.choice(apps_by_dept[person["department"]])
        prompt = rng.choice(_SENSITIVE if rng.random() < _PII_PROB[person["profile"]] else _ROUTINE)
        events.append(_synthetic_event(rng, active, tenant, ts, person, app, prompt))

    events.sort(key=lambda e: e["ts"])
    for i in range(0, len(events), 500):
        await audit.append(events[i:i + 500], notify=False)
    log.info("seeded %d synthetic users and %d historical events", len(people), len(events))


def _synthetic_event(rng, active, tenant, ts, person, app, prompt, source: str = "seed") -> dict:
    pii_types = [d.pii_type for d in detect(prompt)]
    decision = policy.evaluate(active, person["department"], pii_types, prompt)
    vault = Vault()
    redacted, _ = redact(prompt, vault)
    tier = policy.cap_tier(routing.choose_tier(redacted, 1), decision.max_tier)
    in_tok, out_tok = rng.randint(250, 1400), rng.randint(120, 450)
    full = routing.cost(tier, in_tok, out_tok)
    base = {
        "tenant_id": tenant, "ts": ts, "request_id": uuid.uuid4(), "source": source,
        "endpoint": "/v1/chat/completions", "app_id": app["id"], "app_name": app["name"],
        "end_user_id": person["id"], "department": decision.department,
        "department_label": decision.department_label, "policy_version": decision.policy_version,
        "flags": decision.flags, "prompt_redacted": redacted, "pii_types": pii_types, "pii_count": len(pii_types),
        "model_requested": "gpt-4o",
    }
    if not decision.allowed:
        return {**base, "decision": "blocked", "policy_reason": decision.reason,
                "response_redacted": "[request blocked by policy]", "gateway_overhead_ms": rng.randint(4, 30)}
    hit = rng.random() < 0.38
    return {
        **base, "decision": "allowed", "response_redacted": "Synthetic historical response.",
        "cache_hit": hit, "cache_similarity": round(rng.uniform(0.93, 0.995), 3) if hit else None,
        "model_used": "cache" if hit else routing.model_for(tier), "provider": "cache" if hit else "gemini",
        "tier": "cached" if hit else tier, "input_tokens": in_tok, "output_tokens": out_tok,
        "cost_usd": 0.0 if hit else full, "cost_if_no_cache": full,
        "latency_ms": rng.randint(25, 90) if hit else rng.randint(600, 3200),
        "gateway_overhead_ms": rng.randint(8, 60), "rehydrated": len(vault),
    }
